"""
    source_key(p::Problem) -> Symbol

Return the symbol under which `p` is registered in this module.
"""
source_key(p::Problem) = Symbol(p.name)

"""
    source_of(p::Problem) -> Symbol

Return the SyGuS `PBE_SLIA_Track_2019` subdirectory (`:euphony` or `:from_2018`)
that `p` was sourced from.
"""
source_of(p::Problem) = PBE_SLIA_TRACK_2019_SOURCES[source_key(p)]

_is_problem_name(name::Symbol) = startswith(string(name), "problem_") && getfield(@__MODULE__, name) isa Problem

"""
    all_problems() -> Vector{Problem}

Return all PBE_SLIA_Track_2019 problems.
"""
all_problems() = [getfield(@__MODULE__, name) for name in names(@__MODULE__; all=true) if _is_problem_name(name)]

"""
    euphony_problems() -> Vector{Problem}

Return the PBE_SLIA_Track_2019 problems sourced from the `euphony` track.
"""
euphony_problems() = filter(p -> source_of(p) == :euphony, all_problems())

"""
    from_2018_problems() -> Vector{Problem}

Return the PBE_SLIA_Track_2019 problems sourced from the `from_2018` track.
"""
from_2018_problems() = filter(p -> source_of(p) == :from_2018, all_problems())
